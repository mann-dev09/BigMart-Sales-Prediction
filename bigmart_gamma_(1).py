"""### 1.2 Import the tools
pandas handles tables; NumPy performs calculations; sklearn trains and evaluates the model; joblib saves it; matplotlib draws graphs.
"""

from pathlib import Path
import json
import numpy as np
import pandas as pd
import joblib
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from sklearn.preprocessing import OneHotEncoder, SplineTransformer
from sklearn.linear_model import GammaRegressor
from sklearn.model_selection import train_test_split, KFold
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

ROOT = Path(__file__).resolve().parent if '__file__' in globals() else Path.cwd()
TARGET = 'Item_Outlet_Sales'
KEYS = ['Item_Identifier', 'Outlet_Identifier']

"""### 1.3 Read the three CSV files
Train contains known sales. Test needs predictions. The sample provides the submission format.
"""

folder = ROOT / 'results'
folder.mkdir(exist_ok=True)
train = pd.read_csv(ROOT / 'data/train.csv')
test = pd.read_csv(ROOT / 'data/test.csv')
template = pd.read_csv(ROOT / 'data/sample_submission.csv')
print('Train:', train.shape, 'Test:', test.shape)
print(train.head().to_string(index=False))

"""### 1.4 Inspect missing values
Weight and outlet size are not used by this model, so their missing values do not need imputation.
"""

print(train.isna().sum())
train.isna().sum().to_csv(folder / 'missing_values.csv')

"""### 1.5 Check the inputs
An assert stops the program if a required condition fails. MRP and target sales must be positive for this design.
"""

for frame in (train, test):
    assert frame[KEYS + ['Item_MRP']].notna().all().all()
    assert (frame.Item_MRP > 0).all()
    assert not frame[KEYS].duplicated().any()
assert (train[TARGET] > 0).all()
assert template[KEYS].equals(test[KEYS])
print('Input checks passed.')

"""## Part 2 — Build the model inputs

### 2.1 Extract the product number
For FDA15, extract 15. reshape(-1, 1) makes the single-column matrix sklearn expects. This is an empirical ID pattern, not a physical product property.
"""

def product_number(frame):
    suffix = frame['Item_Identifier'].str.extract(r'(\d+)$')[0]
    numbers = suffix.astype(float).to_numpy()
    return numbers.reshape(-1, 1)

print(product_number(train.head()))

"""### 2.2 Describe how inputs are combined
The encoder creates store indicators. Multiplying these by log(MRP) gives store-specific price effects. The spline represents a smooth product-number curve. transform applies already learned rules.
"""

def encode(frame, encoder, spline):
    store_columns = encoder.transform(frame[['Outlet_Identifier']])
    log_price = np.log(frame['Item_MRP'].to_numpy()).reshape(-1, 1)
    store_price_columns = store_columns * log_price
    product_curve = spline.transform(product_number(frame))
    return np.column_stack([
        store_columns,
        store_price_columns,
        product_curve
    ])

"""### 2.3 Create a reusable training function
fit learns the encoder, spline and Gamma coefficients using only the rows passed in. Keeping these together lets each CV fold learn its own transformations.
"""

def fit_model(frame, sales):
    # Learn which stores occur in these training rows.
    encoder = OneHotEncoder(handle_unknown='ignore', sparse_output=False)
    encoder.fit(frame[['Outlet_Identifier']])

    # Learn the spline basis from these training rows.
    spline = SplineTransformer(n_knots=16, degree=3)
    spline.fit(product_number(frame))

    # Convert inputs, then fit the sales model.
    inputs = encode(frame, encoder, spline)
    estimator = GammaRegressor(alpha=0.0001, max_iter=5000)
    estimator.fit(inputs, sales)
    return {'encoder': encoder, 'spline': spline, 'estimator': estimator}

"""### 2.4 Create a reusable prediction function
Prediction uses the saved transformations and model; it does not learn again.
"""

def predict(bundle, frame):
    inputs = encode(frame, bundle['encoder'], bundle['spline'])
    return bundle['estimator'].predict(inputs)

"""## Part 3 — Train and cross-validate

### 3.1 Define the three scores
Lower RMSE and MAE are better. Higher R-squared is better; it is not classification accuracy.
"""

def scores(actual, estimated):
    rmse = np.sqrt(mean_squared_error(actual, estimated))
    mae = mean_absolute_error(actual, estimated)
    r_squared = r2_score(actual, estimated)
    return {'RMSE': float(rmse), 'MAE': float(mae), 'R2': float(r_squared)}

"""### 3.2 Reserve evaluation rows
80% becomes development data; 20% becomes evaluation data. Seed 42 reproduces the earlier split. That evaluation split has already been inspected.
"""

development, evaluation = train_test_split(
    train, test_size=0.2, random_state=42
)
print('Development rows:', len(development))
print('Evaluation rows:', len(evaluation))

"""### 3.3 Set up five folds
Each development row will be validated once and used for learning in four other folds.
"""

cv = KFold(n_splits=5, shuffle=True, random_state=42)
fold_rows = []

"""### 3.4 Run cross-validation
In every loop: select learning rows, fit transformations and model, predict validation rows, and record errors.
"""

for number, (a, b) in enumerate(cv.split(development), start=1):
    learning = development.iloc[a]
    validation = development.iloc[b]
    fitted = fit_model(learning, learning[TARGET])
    validation_predictions = predict(fitted, validation)
    fold_scores = scores(validation[TARGET], validation_predictions)
    fold_rows.append({'fold': number, **fold_scores})
    print('Fold', number, fold_scores)

"""### 3.5 Summarize the fold results
The mean summarizes performance; the standard deviation describes variation across these folds.
"""

folds = pd.DataFrame(fold_rows)
folds.to_csv(folder / 'cross_validation.csv', index=False)
print(folds)
print('Mean CV RMSE:', folds.RMSE.mean())
print('Fold standard deviation:', folds.RMSE.std(ddof=0))

"""## Part 4 — Evaluate and understand errors

### 4.1 Fit development data and predict evaluation rows
This model learns from all 6,818 development rows. Evaluation labels are used only to calculate the scores.
"""

model = fit_model(development, development[TARGET])
estimates = predict(model, evaluation)
print(scores(evaluation[TARGET], estimates))

"""### 4.2 Compare with a simple average guess
The baseline predicts the development mean for every evaluation row.
"""

baseline_predictions = np.repeat(
    development[TARGET].mean(), len(evaluation)
)
print('Mean baseline:', scores(evaluation[TARGET], baseline_predictions))

"""### 4.3 Save the metrics
This records the scores and the limitation of the previously examined evaluation split.
"""

summary = {'development_rows': len(development), 'evaluation_rows': len(evaluation),
           'cv_rmse_mean': float(folds.RMSE.mean()),
           'cv_rmse_sd': float(folds.RMSE.std(ddof=0)),
           'evaluation': scores(evaluation[TARGET], estimates),
           'mean_baseline': scores(evaluation[TARGET], np.repeat(development[TARGET].mean(),len(evaluation))),
           'evaluation_note': 'Previously examined split: comparative diagnostic, not a new untouched test.'}

(folder / 'metrics.json').write_text(json.dumps(summary, indent=2))
print(json.dumps(summary, indent=2))

"""### 4.4 Inspect individual mistakes
Residual = actual minus predicted. Positive residuals mean the model predicted too little.
"""

details = evaluation[KEYS+[TARGET]].copy()
details['Predicted_Sales'] = estimates
details['Residual'] = details[TARGET] - estimates
details.to_csv(folder / 'evaluation_predictions.csv', index=False)

print(details.head().to_string(index=False))

"""### 4.5 Plot actual against predicted
Points on the dashed diagonal are perfect predictions.
"""

fig, ax = plt.subplots(1, 2, figsize=(11, 4))
ax[0].scatter(evaluation[TARGET], estimates, s=9, alpha=.25, color='teal')
limit = max(evaluation[TARGET].max(), estimates.max())
ax[0].plot([0, limit], [0, limit], '--', color='orange')
ax[0].set(xlabel='Actual sales', ylabel='Predicted sales', title='Evaluation predictions')

"""### 4.6 Plot residuals and display the figure
This completes the figure started in the previous cell. Look for large errors and systematic underprediction.
"""

ax[1].scatter(estimates, details.Residual, s=9, alpha=.25, color='teal')
ax[1].axhline(0, color='orange', linestyle='--')
ax[1].set(xlabel='Predicted sales', ylabel='Actual - predicted', title='Residuals')
fig.tight_layout()
fig.savefig(folder / 'diagnostics.png', dpi=150)
plt.close(fig)
